"""Pack the ending title into the original four 128x32 4bpp logo strips."""

import argparse
from pathlib import Path

from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    with Image.open(args.source) as image:
        if image.mode != "P" or image.size != (448, 32):
            parser.error("expected a 448x32 indexed title")
        if max(image.tobytes()) > 15:
            parser.error("the title must use at most 16 palette entries")
        atlas = Image.new("P", (128, 128))
        for i in range(4):
            atlas.paste(image.crop((i * 128, 0, min((i + 1) * 128, 448), 32)),
                        (0, i * 32))
        pixels = atlas.tobytes()
        words = [sum(pixels[i + j] << (j * 4) for j in range(4))
                 for i in range(0, len(pixels), 4)]
        palette = image.getpalette()
        colors = [0] + [(palette[i * 3] >> 3) |
                        ((palette[i * 3 + 1] >> 3) << 5) |
                        ((palette[i * 3 + 2] >> 3) << 10)
                        for i in range(1, 16)]
    chunks = ["// Generated by tools/build_ending_title.py; clang-format off"]
    for name, values in (("ending_title_pixels", words),
                         ("ending_title_palette", colors)):
        chunks.append(f"static u16 {name}[] = {{")
        chunks.extend(", ".join(f"0x{v:04X}" for v in values[i:i + 12]) + ","
                      for i in range(0, len(values), 12))
        chunks.append("};")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(chunks) + "\n")


if __name__ == "__main__":
    main()
